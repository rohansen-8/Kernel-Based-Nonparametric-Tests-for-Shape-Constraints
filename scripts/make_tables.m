%% Shape-test tables of the paper from saved results only (no estimation): Tables 5.1-5.4.
%   Reads results/ (run_empirical.m) and writes LaTeX and CSV versions to tables/.
root = fileparts(fileparts(mfilename("fullpath")));          % repository root (this file is in scripts/)
results_dir = fullfile(root, "results");
table_dir = fullfile(root, "tables");
if ~isfolder(table_dir), mkdir(table_dir); end

labels = ["Size", "Book-to-Market", "Cash Flow-to-Price", "Earnings-to-Price", "Dividend Yield", ...
    "Momentum", "Short-Term Reversal", "Long-Term Reversal"];            % E2 row labels, same order as e2_tests

%% E1: shape-test table
load(fullfile(results_dir, "e1_tests.mat"), "e1_tests");
e1_table = array2table(e1_tests.p_value', "VariableNames", ["Low beta", "Market beta", "High beta"], ...
    "RowNames", ["Weakly increasing", "Weakly decreasing"]);
writetable(e1_table, fullfile(table_dir, "e1_shape_tests.csv"), "WriteRowNames", true);
t = e1_tests; P = t.p_value';                          % restriction x region
body = ["Weakly increasing"; "Weakly decreasing"] + " & " + join(arrayfun(@p_cell, P), " & ", 2) + " \\";
note = "\footnotesize\textit{Notes:} Entries are $p$-values of the cone-Wald test of the null hypothesis that " + ...
    "expected excess returns are weakly increasing or weakly decreasing in market beta within each beta region. " + ...
    sprintf("The sample has $T = %d$ months. The long-run covariance is estimated by Newey--West with %d lags, ", t.T, t.n_lags) + ...
    sprintf("and $p$-values are calibrated with %s Gaussian draws. ", format_thousands(t.B)) + ...
    "$^{***}$, $^{**}$ and $^{*}$ denote $p < 0.01$, $p < 0.05$ and $p < 0.10$.";
writelines(["\begin{table}[!htbp]"; "\centering"; ...
    "\caption{Shape tests for expected excess returns and market beta}"; "\label{tab:e1_shape_tests}"; ...
    "\begin{tabular}{lccc}"; "\toprule"; ...
    " & Low Beta & Market Beta & High Beta \\"; ...
    " & " + join(compose("$[%g, %g]$", t.regions), " & ") + " \\"; ...
    "\midrule"; body; "\bottomrule"; "\end{tabular}"; ...
    "\par\medskip"; "\begin{minipage}{\linewidth}"; note; "\end{minipage}"; "\end{table}"], ...
    fullfile(table_dir, "e1_shape_tests.tex"));

%% E2: regional shape-test table (p-values with significance stars)
load(fullfile(results_dir, "e2_tests.mat"), "e2_tests");
P = cat(3, e2_tests.p_value);                         % region x direction x characteristic
names = [e2_tests.name]';
assert(isequal(lower(names'), lower(labels)));        % same order as the E2 figure
t = e2_tests(1);
assert(all([e2_tests.T] == t.T & [e2_tests.n_lags] == t.n_lags & [e2_tests.B] == t.B));
panel_titles = ["Panel A: H0 weakly increasing", "Panel B: H0 weakly decreasing"];   % E3 and E4 tables
body = strings(0, 1);
for k = 1:numel(labels)
    if k > 1, body(end + 1) = "\addlinespace"; end %#ok<SAGROW>
    body(end + 1) = "\multicolumn{4}{l}{\textbf{" + labels(k) + "}} \\"; %#ok<SAGROW>
    body = [body; "\quad " + ["Weakly increasing"; "Weakly decreasing"] + " & " + ...
        join(arrayfun(@p_cell, P(:, :, k)'), " & ", 2) + " \\"]; %#ok<AGROW>
end
bounds = @(k) join(compose("[%s, %s]", arrayfun(@num_text, e2_tests(k).regions_original)), ", ");
regions_text = join(arrayfun(@(k) labels(k) + " " + bounds(k), 1:numel(labels)), "; ");
note = "Entries are $p$-values of the cone-Wald test of the null hypothesis that expected excess returns are " + ...
    "weakly increasing or weakly decreasing in the characteristic within each region. Regions 1--3 are, in order: " + ...
    replace(regions_text, "Size ", "Size (market equity, USD millions) ") + ". " + ...
    sprintf("The sample has $T = %d$ months. The long-run covariance is estimated by Newey--West with %d lags, ", t.T, t.n_lags) + ...
    sprintf("and $p$-values are calibrated with %s Gaussian draws. ", format_thousands(t.B)) + ...
    "$^{***}$, $^{**}$ and $^{*}$ denote $p < 0.01$, $p < 0.05$ and $p < 0.10$.";
write_table_tex(fullfile(table_dir, "e2_shape_tests.tex"), ...
    "Shape tests for expected excess returns and firm characteristics", "tab:e2_shape_tests", ...
    " & Region 1 & Region 2 & Region 3 \\", body, note);
pv = reshape(permute(P, [3 1 2]), numel(names), 6);
writetable(array2table(pv, "RowNames", names, "VariableNames", ["inc_R1", "inc_R2", "inc_R3", "dec_R1", "dec_R2", "dec_R3"]), ...
    fullfile(table_dir, "e2_shape_tests.csv"), "WriteRowNames", true);

%% E3: regional shape-test table
load(fullfile(results_dir, "e3_tests.mat"), "e3_tests");
P = cat(3, e3_tests.p_value);                         % region x direction x subsample
rows = compose("%d-%d", vertcat(e3_tests.subsample));
fmt = @(p) string(sprintf("%.3f", p)) + string(repmat('*', 1, (p < 0.10) + (p < 0.05) + (p < 0.01)));   % E4 table
assert(all(arrayfun(@(t) isequal(t.regions, e3_tests(1).regions) && t.B == e3_tests(1).B, e3_tests)));
body = strings(0, 1);
for s = 1:numel(e3_tests)
    if s > 1, body(end + 1) = "\midrule"; end %#ok<SAGROW>
    body(end + 1) = sprintf("\\multicolumn{4}{l}{\\textbf{Panel %c: %d--%d} ($T = %d$)} \\\\", ...
        'A' + s - 1, e3_tests(s).subsample, e3_tests(s).T); %#ok<SAGROW>
    body = [body; "\quad " + ["Weakly increasing"; "Weakly decreasing"] + " & " + ...
        join(arrayfun(@p_cell, P(:, :, s)'), " & ", 2) + " \\"]; %#ok<AGROW>

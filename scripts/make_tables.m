writetable(array2table(reshape(P, numel(rows), 6), "RowNames", rows, ...
    "VariableNames", ["inc_R1", "inc_R2", "inc_R3", "dec_R1", "dec_R2", "dec_R3"]), ...
    fullfile(table_dir, "e4_shape_tests.csv"), "WriteRowNames", true);

function c = p_cell(p)
%% Table cell for a p-value: three decimals ("< 0.001" below 0.001) and stars set from the exact p-value.
if p < 0.001, c = "\llap{$<$\,}0.001"; else, c = string(sprintf("%.3f", p)); end
n = (p < 0.10) + (p < 0.05) + (p < 0.01);
if n > 0, c = c + "\rlap{$^{" + repmat('*', 1, n) + "}$}"; end   % zero-width "<" and stars keep the numbers aligned
end

function s = format_thousands(n)
%% Integer with comma thousands separators (10000 -> "10,000").
s = regexprep(sprintf("%d", n), "\d(?=(\d{3})+$)", "$0,");
end

function s = num_text(x)
%% Region bound for table notes: thousands separators from 1,000 and a typeset minus sign.
if abs(x) >= 1000, s = format_thousands(abs(x)); else, s = string(sprintf("%g", abs(x))); end
if x < 0, s = "$-$" + s; end
end

function write_table_tex(file, caption, label, header, body, note)
%% booktabs table float (label column and three centred p-value columns) with full-width notes below.
writelines(["\begin{table}[!htbp]"; "\centering"; "\caption{" + caption + "}"; "\label{" + label + "}"; ...
    "\begin{tabular}{lccc}"; "\toprule"; header(:); "\midrule"; body(:); "\bottomrule"; "\end{tabular}"; ...
    "\par\medskip"; "\begin{minipage}{\linewidth}"; "\footnotesize\textit{Notes:} " + note; "\end{minipage}"; ...
    "\end{table}"], file);
end
